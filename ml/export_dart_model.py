"""
SmartKavach ML Pipeline — Dart Model Exporter
Converts ml/model_weights.json into a standalone, zero-dependency Dart class
(lib/ml_crash_classifier.dart) for blazing-fast in-app inference (<0.1ms).
"""

import json

def generate_dart_code():
    with open("ml/model_weights.json", "r") as f:
        data = json.load(f)

    mean = data["scaler"]["mean"]
    scale = data["scaler"]["scale"]
    layers = data["layers"]

    _layer0_in = len(layers[0]["weights"])
    _layer0_out = len(layers[0]["biases"])
    _layer1_in = len(layers[1]["weights"])
    _layer1_out = len(layers[1]["biases"])
    _layer2_in = len(layers[2]["weights"])
    _layer2_out = len(layers[2]["biases"])

    dart_code = f"""// AUTO-GENERATED BY ml/export_dart_model.py
// DO NOT EDIT DIRECTLY. Run `python ml/export_dart_model.py` to regenerate.

import 'dart:math' as math;

enum RideEventClass {{
  normalRiding,
  pothole,
  droppedPhone,
  severeCrash,
}}

/// Lightweight, embedded ML inference engine for motorcycle crash verification.
/// Computes 21 statistical & kinematic features and executes an MLP forward pass.
class MlCrashClassifier {{
  static const List<double> _mean = {mean};
  static const List<double> _scale = {scale};

  static const List<List<double>> _layer0Weights = {layers[0]["weights"]};
  static const List<double> _layer0Biases = {layers[0]["biases"]};

  static const List<List<double>> _layer1Weights = {layers[1]["weights"]};
  static const List<double> _layer1Biases = {layers[1]["biases"]};

  static const List<List<double>> _layer2Weights = {layers[2]["weights"]};
  static const List<double> _layer2Biases = {layers[2]["biases"]};

  /// Extracts 21 statistical, kinematic, and stillness features from a 50x7 window.
  /// Window format: 50 time steps of [acc_x, acc_y, acc_z, gyro_x, gyro_y, gyro_z, speed_kmh]
  static List<double> extractFeatures(List<List<double>> window) {{
    assert(window.length == 50, 'Window must contain exactly 50 samples');

    final accMag = <double>[];
    final gyroMag = <double>[];

    var accXMin = double.infinity, accXMax = -double.infinity;
    var accYMin = double.infinity, accYMax = -double.infinity;
    var accZMin = double.infinity, accZMax = -double.infinity;

    var gyroXMin = double.infinity, gyroXMax = -double.infinity;
    var gyroYMin = double.infinity, gyroYMax = -double.infinity;
    var gyroZMin = double.infinity, gyroZMax = -double.infinity;

    for (int i = 0; i < 50; i++) {{
      final sample = window[i];
      final ax = sample[0], ay = sample[1], az = sample[2];
      final gx = sample[3], gy = sample[4], gz = sample[5];

      accMag.add(math.sqrt(ax * ax + ay * ay + az * az));
      gyroMag.add(math.sqrt(gx * gx + gy * gy + gz * gz));

      if (ax < accXMin) accXMin = ax;
      if (ax > accXMax) accXMax = ax;
      if (ay < accYMin) accYMin = ay;
      if (ay > accYMax) accYMax = ay;
      if (az < accZMin) accZMin = az;
      if (az > accZMax) accZMax = az;

      if (gx < gyroXMin) gyroXMin = gx;
      if (gx > gyroXMax) gyroXMax = gx;
      if (gy < gyroYMin) gyroYMin = gy;
      if (gy > gyroYMax) gyroYMax = gy;
      if (gz < gyroZMin) gyroZMin = gz;
      if (gz > gyroZMax) gyroZMax = gz;
    }}

    // Accel resultant stats
    final accMagMax = accMag.reduce(math.max);
    final accMagRms = math.sqrt(accMag.map((v) => v * v).reduce((a, b) => a + b) / 50.0);
    final accMagP2p = accMagMax - accMag.reduce(math.min);
    final accMagMean = accMag.reduce((a, b) => a + b) / 50.0;
    final accMagStd = math.sqrt(accMag.map((v) => (v - accMagMean) * (v - accMagMean)).reduce((a, b) => a + b) / 50.0);

    // Gyro resultant stats
    final gyroMagMax = gyroMag.reduce(math.max);
    final gyroMagRms = math.sqrt(gyroMag.map((v) => v * v).reduce((a, b) => a + b) / 50.0);
    final gyroMagP2p = gyroMagMax - gyroMag.reduce(math.min);
    final gyroMagMean = gyroMag.reduce((a, b) => a + b) / 50.0;
    final gyroMagStd = math.sqrt(gyroMag.map((v) => (v - gyroMagMean) * (v - gyroMagMean)).reduce((a, b) => a + b) / 50.0);

    // Speed kinematics
    var speedInitSum = 0.0;
    for (int i = 0; i < 10; i++) {{
      speedInitSum += window[i][6];
    }}
    final speedInit = speedInitSum / 10.0;

    var speedFinalSum = 0.0;
    for (int i = 40; i < 50; i++) {{
      speedFinalSum += window[i][6];
    }}
    final speedFinal = speedFinalSum / 10.0;
    final speedDelta = speedInit - speedFinal;

    // Last 15 samples post-stillness
    var postSpeedSum = 0.0;
    for (int i = 35; i < 50; i++) {{
      postSpeedSum += window[i][6];
    }}
    final postSpeedMean = postSpeedSum / 15.0;

    var postSpeedVarSum = 0.0;
    for (int i = 35; i < 50; i++) {{
      final diff = window[i][6] - postSpeedMean;
      postSpeedVarSum += diff * diff;
    }}
    final speedPostVar = postSpeedVarSum / 15.0;

    // Post acc & gyro std (last 15 samples)
    var postAccMean = 0.0, postGyroMean = 0.0;
    for (int i = 35; i < 50; i++) {{
      for (int k = 0; k < 3; k++) {{
        postAccMean += window[i][k];
        postGyroMean += window[i][3 + k];
      }}
    }}
    postAccMean /= 45.0;
    postGyroMean /= 45.0;

    var postAccStdSum = 0.0, postGyroStdSum = 0.0;
    for (int i = 35; i < 50; i++) {{
      for (int k = 0; k < 3; k++) {{
        final ad = window[i][k] - postAccMean;
        postAccStdSum += ad * ad;
        final gd = window[i][3 + k] - postGyroMean;
        postGyroStdSum += gd * gd;
      }}
    }}
    final postAccStd = math.sqrt(postAccStdSum / 45.0);
    final postGyroStd = math.sqrt(postGyroStdSum / 45.0);

    return [
      accMagMax, accMagRms, accMagP2p, accMagStd,
      gyroMagMax, gyroMagRms, gyroMagP2p, gyroMagStd,
      speedInit, speedFinal, speedDelta, speedPostVar,
      accXMax - accXMin, accYMax - accYMin, accZMax - accZMin,
      gyroXMax - gyroXMin, gyroYMax - gyroYMin, gyroZMax - gyroZMin,
      postAccStd, postGyroStd, postSpeedMean
    ];
  }}

  /// Runs forward inference and returns probability distribution across classes.
  static Map<RideEventClass, double> predictProbabilities(List<List<double>> window) {{
    final features = extractFeatures(window);

    // 1. Scale features
    final scaled = List<double>.generate(21, (i) => (features[i] - _mean[i]) / _scale[i]);

    // 2. Layer 0 (21 -> {_layer0_out}, ReLU)
    final h0 = List<double>.filled({_layer0_out}, 0.0);
    for (int j = 0; j < {_layer0_out}; j++) {{
      double sum = _layer0Biases[j];
      for (int i = 0; i < {_layer0_in}; i++) {{
        sum += scaled[i] * _layer0Weights[i][j];
      }}
      h0[j] = math.max(0.0, sum); // ReLU
    }}

    // 3. Layer 1 ({_layer1_in} -> {_layer1_out}, ReLU)
    final h1 = List<double>.filled({_layer1_out}, 0.0);
    for (int j = 0; j < {_layer1_out}; j++) {{
      double sum = _layer1Biases[j];
      for (int i = 0; i < {_layer1_in}; i++) {{
        sum += h0[i] * _layer1Weights[i][j];
      }}
      h1[j] = math.max(0.0, sum); // ReLU
    }}

    // 4. Layer 2 ({_layer2_in} -> {_layer2_out}, Softmax)
    final logits = List<double>.filled({_layer2_out}, 0.0);
    double maxLogit = -double.infinity;
    for (int j = 0; j < {_layer2_out}; j++) {{
      double sum = _layer2Biases[j];
      for (int i = 0; i < {_layer2_in}; i++) {{
        sum += h1[i] * _layer2Weights[i][j];
      }}
      logits[j] = sum;
      if (sum > maxLogit) maxLogit = sum;
    }}

    // Numerically stable softmax
    final expScores = List<double>.generate(4, (i) => math.exp(logits[i] - maxLogit));
    final expSum = expScores.reduce((a, b) => a + b);

    return {{
      RideEventClass.normalRiding: expScores[0] / expSum,
      RideEventClass.pothole: expScores[1] / expSum,
      RideEventClass.droppedPhone: expScores[2] / expSum,
      RideEventClass.severeCrash: expScores[3] / expSum,
    }};
  }}

  /// Returns the top predicted class.
  static RideEventClass predict(List<List<double>> window) {{
    final probs = predictProbabilities(window);
    RideEventClass topClass = RideEventClass.normalRiding;
    double maxP = -1.0;
    probs.forEach((cls, p) {{
      if (p > maxP) {{
        maxP = p;
        topClass = cls;
      }}
    }});
    return topClass;
  }}
}}
"""
    with open("lib/ml_crash_classifier.dart", "w") as f:
        f.write(dart_code)
    print("Exported pure-Dart inference engine to lib/ml_crash_classifier.dart")

if __name__ == "__main__":
    generate_dart_code()
