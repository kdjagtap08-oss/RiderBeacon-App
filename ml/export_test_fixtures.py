"""
Exports representative test windows generated by dataset_loader for unit testing in Flutter.
"""
import json
import os
from dataset_loader import generate_window

os.makedirs("test/fixtures", exist_ok=True)

fixtures = {
    "normal": generate_window(label=0, random_seed=123).tolist(),
    "pothole": generate_window(label=1, random_seed=456).tolist(),
    "dropped_phone": generate_window(label=2, random_seed=789).tolist(),
    "severe_crash": generate_window(label=3, random_seed=101112).tolist(),
}

with open("test/fixtures/ml_test_windows.json", "w") as f:
    json.dump(fixtures, f, indent=2)

print("Exported fixtures to test/fixtures/ml_test_windows.json")
